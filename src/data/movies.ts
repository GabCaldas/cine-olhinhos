const MOVIES_STORAGE_KEY = 'horror_night_movies_v3';

export function loadMovies(): MovieTemplate[] {
  try {
    const saved = localStorage.getItem(MOVIES_STORAGE_KEY);
    if (!saved) return INITIAL_MOVIES;
    const parsed = JSON.parse(saved);
    if (Array.isArray(parsed)) {
      return parsed;
    }
    return INITIAL_MOVIES;
  } catch {
    return INITIAL_MOVIES;
  }
}

export function saveMovies(movies: MovieTemplate[]): void {
  try {
    localStorage.setItem(MOVIES_STORAGE_KEY, JSON.stringify(movies));
  } catch {
    // Ignore storage errors
  }
}

export function resetMoviesToDefault(): MovieTemplate[] {
  try {
    localStorage.removeItem(MOVIES_STORAGE_KEY);
  } catch {
    // Ignore
  }
  return INITIAL_MOVIES;
}
